/**
 * Plenty's built-in grocery catalog.
 *
 * ~400 canonical products with realistic package sizes, shelf lives,
 * consumption priors, substitution groups, allergen flags and the receipt
 * spellings needed to recognise them. Australian-first (capsicum, coriander,
 * zucchini, mince, rocket, prawns) with UK/US/NZ synonyms as aliases.
 *
 * Calibration notes for `dailyUsePerPerson` (per adult-equivalent per day):
 * two adults finish a 2 L milk in about five days (0.2 L), a loaf in about
 * four days (0.12), a dozen eggs in about two weeks (0.4). Only continuously
 * consumed products get a prior; recipe-driven ingredients don't.
 *
 * Pure data. Aliases are lower-case; the matcher cleans and singularises them
 * the same way it cleans receipt text.
 */

import type { CatalogProduct } from "@/lib/catalog/types";

type SectionDefaults = Pick<CatalogProduct, "aisle" | "location" | "perishable"> & Pick<CatalogProduct, "nonFood">;
type ProductSpec = Omit<CatalogProduct, "aisle" | "location" | "perishable"> & Partial<SectionDefaults>;

function section(defaults: SectionDefaults, specs: ProductSpec[]): CatalogProduct[] {
  return specs.map((spec) => ({ ...defaults, ...spec }));
}

